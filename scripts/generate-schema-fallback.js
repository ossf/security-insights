#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const CueParser = require('../docs/editor/js/cue-parser.js');

const repositoryRoot = path.resolve(__dirname, '..');
const schemaPath = path.join(repositoryRoot, 'spec', 'schema.cue');
const versionPath = path.join(repositoryRoot, 'VERSION');
const outputPath = path.join(
  repositoryRoot,
  'docs',
  'editor',
  'js',
  'schema-fallback.js'
);

function generate() {
  const source = fs.readFileSync(schemaPath, 'utf8');
  const version = fs.readFileSync(versionPath, 'utf8').trim().replace(/^v/, '');
  const schema = CueParser.parse(source, { version });
  const serializedTypes = JSON.stringify(schema.types, null, 2);

  return `/**
 * Generated from spec/schema.cue and VERSION.
 * Do not edit this file directly; run make generate-schema-fallback.
 */
const SchemaFallbackParser = typeof CueParser !== 'undefined'
  ? CueParser
  : require('./cue-parser.js');

const SchemaFallback = SchemaFallbackParser.createSchema(
${serializedTypes},
  { version: ${JSON.stringify(version)} }
);

if (typeof module !== 'undefined' && module.exports) {
  module.exports = SchemaFallback;
}
`;
}

const expected = generate();
if (process.argv.includes('--check')) {
  const actual = fs.existsSync(outputPath)
    ? fs.readFileSync(outputPath, 'utf8')
    : '';
  if (actual !== expected) {
    console.error('docs/editor/js/schema-fallback.js is out of date.');
    console.error('Run: make generate-schema-fallback');
    process.exit(1);
  }
} else {
  fs.writeFileSync(outputPath, expected);
  console.log('Generated docs/editor/js/schema-fallback.js');
}
